import hashlib
import json
import os
import re
import time
from datetime import datetime, timezone

import yaml

BUNDLE_NAME = "cx-genie-semantic-agents"
KEY_RE = re.compile(r"^[a-z][a-z0-9_]*$")
SCHEMA_RE = re.compile(r"^[A-Za-z0-9_]+\.[A-Za-z0-9_]+$")
TERMINAL = ("DONE", "EVALUATION_FAILED", "EVALUATION_CANCELLED", "EVALUATION_TIMEOUT")


def check_key(key):
    """Resource key of an agent: lowercase, starts with a letter, letters/digits/underscores. Never rename it later."""
    if not KEY_RE.match(key or ""):
        raise ValueError(f"invalid agent key {key!r}: use lowercase letters, digits and _ (e.g. cx_insights)")
    return key


def check_schema(fqn, field):
    if not SCHEMA_RE.match(fqn or ""):
        raise ValueError(f"{field} must be catalog.schema, got {fqn!r}")
    return fqn


def _schema_pattern(schema_fqn):
    catalog, schema = schema_fqn.split(".")
    part = lambda p: rf"(?:`{re.escape(p)}`|{re.escape(p)})"
    return re.compile(rf"(?<![\w`.]){part(catalog)}\.{part(schema)}(?=\.)", re.IGNORECASE)


def mv_sql_template(show_create, dev_schema):
    """SHOW CREATE TABLE output of a metric view → CREATE OR REPLACE with <catalog>.<schema> placeholders, one final ';'."""
    if "WITH METRICS" not in show_create.upper():
        raise ValueError("not a metric view (no WITH METRICS)")
    pat = _schema_pattern(dev_schema)
    if not pat.search(show_create):
        raise ValueError(f"the view does not reference {dev_schema}: check the dev schema field")
    out = pat.sub("<catalog>.<schema>", show_create.strip().rstrip(";"))
    out = re.sub(r"^\s*CREATE\s+(?:OR\s+REPLACE\s+)?VIEW", "CREATE OR REPLACE VIEW", out, count=1, flags=re.IGNORECASE)
    return out + ";\n"


def canonical_json(serialized_space):
    """Stable text of an agent definition: sorted keys, 2-space indent. List order is kept (the API sorts its collections)."""
    return json.dumps(json.loads(serialized_space), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def sha256(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


class _Block(str):
    pass


yaml.SafeDumper.add_representer(_Block, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def _dump(doc, header):
    return header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)


def render_space_yaml(key, title, description):
    doc = {"resources": {"genie_spaces": {check_key(key): {
        "title": title,
        "description": _Block(description) if "\n" in (description or "") else (description or ""),
        "warehouse_id": "${var.warehouse_id}",
        "parent_path": "${var.agents_folder}",
        "file_path": f"../src/{key}.geniespace.json",
        "permissions": [
            {"level": "CAN_MANAGE", "group_name": "${var.owners_group}"},
            {"level": "CAN_RUN", "group_name": "${var.users_group}"},
            {"level": "CAN_RUN", "group_name": "${var.testers_group}"},
        ],
        "lifecycle": {"prevent_destroy": True},
    }}}}
    return _dump(doc, f"# Generated by save_and_benchmark from the dev agent. Never rename the key '{key}': a new key = a new agent.\n")


def render_databricks_yml(s):
    prod_ws = {"host": s["prod_host"], "root_path": s["prod_root_path"]}
    prod = {"mode": "production", "workspace": prod_ws,
            "variables": {"warehouse_id": s["prod_warehouse_id"], "gold_schema": s["prod_schema"]}}
    if s.get("prod_run_as"):
        prod["run_as"] = {"service_principal_name": s["prod_run_as"]}
    doc = {
        "bundle": {"name": BUNDLE_NAME, "engine": "direct"},
        "python": {"venv_path": ".venv", "mutators": ["genie_agent_retarget:retarget_genie_spaces"]},
        "include": ["resources/*.yml"],
        "variables": {
            "warehouse_id": {"description": "SQL warehouse used by the agents in this environment"},
            "agents_folder": {"default": s["agents_folder"]},
            "owners_group": {"default": s["groups"]["owners"]},
            "users_group": {"default": s["groups"]["users"]},
            "testers_group": {"default": s["groups"]["testers"]},
            "gold_schema": {"description": "catalog.schema of the metric views in this environment"},
            "genie_table_mapping": {"type": "complex", "default": {s["dev_schema"]: "${var.gold_schema}"}},
        },
        "targets": {
            "dev": {"mode": "development", "default": True,
                    "workspace": {"host": s.get("dev_host", "")},
                    "variables": {"warehouse_id": s["dev_warehouse_id"], "gold_schema": s["dev_schema"]}},
            "prod": prod,
        },
    }
    return _dump(doc, "# Generated by save_and_benchmark from settings.yml. Change the notebook fields, not this file.\n"
                      "# prod root_path is fixed and shared: the deployment state lives there, so agents are updated in place.\n")


def no_gold_ids(definition):
    """Benchmarks without a gold SQL (e.g. negative ones judged on an evaluation note): reported, never scored."""
    qs = json.loads(definition).get("benchmarks", {}).get("questions", [])
    return {q["id"] for q in qs if not any(a.get("content") for a in q.get("answer") or [])}


def benchmark_summary(details, unscored=frozenset()):
    """Score = GOOD / benchmarks with a gold SQL. NEEDS_REVIEW on a scored benchmark counts as not passing."""
    qs = {}
    for d in details:
        qid = d.get("benchmark_question_id") or d.get("question")
        q = {"question": d.get("question", ""), "assessment": d.get("assessment", "UNKNOWN"), "scored": qid not in unscored}
        if d.get("assessment_reasons"):
            q["reasons"] = d["assessment_reasons"]
        qs[qid] = q
    scored = [q for q in qs.values() if q["scored"]]
    count = lambda a: sum(1 for q in scored if q["assessment"] == a)
    return {"total": len(qs), "scored": len(scored), "good": count("GOOD"), "bad": count("BAD"),
            "needs_review": count("NEEDS_REVIEW"), "score": (count("GOOD") / len(scored)) if scored else 0.0, "questions": qs}


def other_schemas(definition, dev_schema):
    """Schemas of the agent's tables, metric views and functions other than dev_schema (each needs its own mapping rule)."""
    d = json.loads(definition)
    idents = [t.get("identifier", "") for t in d.get("data_sources", {}).get("tables", [])]
    idents += [t.get("identifier", "") for t in d.get("data_sources", {}).get("metric_views", [])]
    idents += [f.get("identifier", "") for f in d.get("instructions", {}).get("sql_functions", [])]
    schemas = {".".join(i.replace("`", "").split(".")[:2]) for i in idents if i.count(".") >= 2}
    return sorted(s for s in schemas if s.lower() != dev_schema.lower())



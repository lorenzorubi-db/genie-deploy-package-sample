def start_eval(w, space_id):
    return w.api_client.do("POST", f"/api/2.0/genie/spaces/{space_id}/eval-runs", body={})["eval_run_id"]


def wait_eval(w, space_id, run_id, poll=30):
    base = f"/api/2.0/genie/spaces/{space_id}/eval-runs/{run_id}"
    while True:
        run = w.api_client.do("GET", base)
        if run["eval_run_status"] in TERMINAL:
            break
        time.sleep(poll)
    if run["eval_run_status"] != "DONE":
        raise RuntimeError(f"benchmark run {run_id} on {space_id} ended {run['eval_run_status']}")
    results, token = [], None
    while True:
        page = w.api_client.do("GET", f"{base}/results", query={"page_token": token} if token else None)
        results += page.get("eval_results", [])
        token = page.get("next_page_token")
        if not token:
            break
    details = []
    for r in results:  # the list has no assessment: it is on each result's detail
        d = w.api_client.do("GET", f"{base}/results/{r['result_id']}")
        details.append({**d, "question": r.get("question"), "benchmark_question_id": r.get("benchmark_question_id")})
    return details

